// Writes THIRD_PARTY_NOTICES.md from the installed production dependency trees. Run from repo root.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

function collect(cwd, extra = []) {
  const tree = JSON.parse(execSync('npm ls --omit=dev --all --json --long', { cwd, maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'ignore'] }).toString());
  const seen = new Map();
  const walk = (deps = {}) => {
    for (const [name, d] of Object.entries(deps)) {
      const key = `${name}@${d.version}`;
      if (!d.version || seen.has(key)) continue;
      let license = 'UNKNOWN';
      try {
        const pj = JSON.parse(readFileSync(path.join(d.path ?? path.join(cwd, 'node_modules', name), 'package.json'), 'utf8'));
        license = typeof pj.license === 'string' ? pj.license : (pj.license?.type ?? pj.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN');
      } catch {}
      seen.set(key, { name, version: d.version, license });
      walk(d.dependencies);
    }
  };
  walk(tree.dependencies);
  for (const e of extra) seen.set(`${e.name}@${e.version}`, e);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const table = (rows) => ['| Package | Version | License |', '|---|---|---|', ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`)].join('\n');
const mobile = collect('apps/mobile', [{ name: 'org.signal:libsignal-android (Maven)', version: '0.105.1', license: 'AGPL-3.0-only' }]);
const server = collect('apps/server');
writeFileSync(
  'THIRD_PARTY_NOTICES.md',
  `# Third-party notices\n\nGenerated by \`node scripts/third-party-notices.mjs\` from installed production dependencies. Full license texts are in each package's directory under node_modules (and in the Maven artifact for libsignal-android).\n\nMap data © OpenStreetMap contributors (ODbL); tiles by OpenFreeMap; style © OpenMapTiles. Fonts: Bricolage Grotesque and Inter (SIL OFL 1.1).\n\n## Android app (${mobile.length} packages)\n\n${table(mobile)}\n\n## API server (${server.length} packages)\n\n${table(server)}\n`,
);
const flagged = [...mobile, ...server].filter((r) => /GPL|UNKNOWN/i.test(r.license));
console.log(`wrote THIRD_PARTY_NOTICES.md; copyleft/unknown: ${flagged.map((r) => `${r.name} (${r.license})`).join(', ') || 'none'}`);
